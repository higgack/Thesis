def fmt_run(r, size=8.5, bold=False):
    r.bold = bold
    r.font.size = Pt(size)
    r.font.name = FONT
    r.element.get_or_add_rPr().get_or_add_rFonts().set(qn('w:eastAsia'), FONT)


def para(cell, text, first=False, size=8.5, bold=False, indent=0, center=False, space_after=2):
    p = cell.paragraphs[0] if first else cell.add_paragraph()
    for i, line in enumerate(text.split('\n')):
        r = p.add_run()
        if i:
            r.add_break()
        r.add_text(line)
        fmt_run(r, size, bold)
    pf = p.paragraph_format
    pf.space_after = Pt(space_after); pf.space_before = Pt(0); pf.line_spacing = 1.15
    if indent:
        pf.left_indent = Mm(indent)
    if center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    return p


def shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement('w:shd')
    sh.set(qn('w:val'), 'clear'); sh.set(qn('w:color'), 'auto'); sh.set(qn('w:fill'), fill)
    tcPr.append(sh)


